// Run with playwright-cli run-code --filename, attached to desktop WebView2.
// Only one synthetic phrase is searched; this never starts a challenge sweep.
async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const state = () => page.evaluate(() => window.__TAURI__.core.invoke('get_state'));
  const initial = await state();
  assert(!initial.active && !['running','paused','pausing','failed'].includes(initial.queue?.status), 'Finish the active search/queue before this test.');
  await page.locator('#new-search').click();
  await page.locator('#video-research>summary').click();
  assert(await page.locator('#video-group option').count() === 4, 'Expected four groups.');
  const post = 'dutch@1 fiber fork dinner cloud live';
  await page.locator('#post').fill(post);
  await page.locator('#video').fill('fog@5 parrot@12 link@3 fiber fiber');
  await page.locator('#apply-video-group').click();
  assert(await page.locator('#video').inputValue() === 'fog@5 parrot@12 link@3 fiber fiber atom basic token dash', 'Pins or multiplicities lost.');
  assert(await page.locator('#post').inputValue() === post, 'Post changed.');
  await page.locator('#apply-video-group').click();
  assert((await page.locator('#video-group-feedback').textContent()).includes('Nenhuma palavra duplicada'), 'Not idempotent.');
  await page.locator('#video-group').selectOption('combined');
  assert((await page.locator('#video-group-words').textContent()).split(' · ').length === 192, 'Combined count wrong.');
  assert(!(await state()).active, 'Applying a group must not start a run.');

  // Independent target generated by mcp/import-fixtures.js address(), checked
  // against the standard BIP39 vector before deriving this invalid-checksum one.
  const target = '0x362a9c55d54da572a7a5853171de8fd04d1da800';
  const phrase = Array(12).fill('abandon').join(' ');
  await page.locator('#mode-template').click();
  await page.locator('#run-name').fill('Verificação · política de checksum');
  await page.locator('#target').fill(target);
  await page.locator('#pattern').fill(phrase);
  await page.locator('#pool').fill('');
  // Fill is blank in a fresh search.
  await page.locator('#backend').selectOption('cpu');
  if (!await page.locator('#max-candidates').isVisible()) await page.locator('.advanced-details>summary').click();
  await page.locator('#max-candidates').fill('1');
  await page.locator('#batch-size').fill('32');
  await page.locator('#no-checksum').check();
  assert(await page.locator('#exclude-ro1').isDisabled(), 'Expanded mode must disable RO1.');
  assert(!await page.locator('#exclude-ro1').isChecked(), 'RO1 remained active.');
  await page.locator('#no-checksum').uncheck();
  assert(!await page.locator('#exclude-ro1').isDisabled(), 'Strict mode should allow RO1 selection again.');
  await page.locator('#start-search').click();

  let strict;
  for(let i=0;i<60;i++) {
    strict=(await state()).runs.find(r=>r.name==='Verificação · política de checksum' && r.config.target===target);
    if(strict && ['completed','covered','failed','found'].includes(strict.status)) break;
    await page.waitForTimeout(200);
  }
  assert(strict && ['completed','covered'].includes(strict.status), `Strict run: ${JSON.stringify(strict)}`);
  await page.locator('#prepare-expanded').waitFor({state:'visible'});
  await page.locator('#prepare-expanded').click();
  assert(await page.locator('#no-checksum').isChecked(), 'Second pass is not expanded.');
  assert(await page.locator('#pattern').inputValue()===phrase, 'Second pass changed phrase.');
  assert(await page.locator('#target').inputValue()===target, 'Second pass changed target.');
  assert(await page.locator('#preparation-note').isVisible(), 'Preparation message missing.');
  assert(!(await state()).active, 'Preparation started a run.');
  await page.locator('#start-search').click();
  let expanded;
  for(let i=0;i<60;i++) {
    expanded=(await state()).runs.find(r=>r.name==='Verificação · política de checksum · sem checksum' && r.config.target===target);
    if(expanded && ['completed','covered','failed','found'].includes(expanded.status)) break;
    await page.waitForTimeout(200);
  }
  assert(expanded?.status==='found', `Expanded run: ${JSON.stringify(expanded)}`);
  assert(expanded.config.noChecksum && !expanded.config.excludeRo1, 'Wrong native policy.');
  assert(expanded.historyExportEligible===false, 'Hit became a negative filter.');
  const old=(await state()).runs.find(r=>r.id===strict.id);
  assert(old && !old.config.noChecksum && old.status===strict.status, 'Original run was changed.');
  await page.waitForFunction(()=>document.querySelector('#run-policy').textContent.includes('Todas as frases'));
  console.log(JSON.stringify({groups:4,distinctWords:192,strict:strict.status,expanded:expanded.status,originalPreserved:true}));
}
